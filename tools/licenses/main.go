// licenses generates THIRD_PARTY_LICENSES.txt: the license texts of the Go
// standard library and of every module compiled into tsnmp (the union of
// the linux and windows amd64 builds, as "go list -deps" reports them).
//
// Usage (from anywhere in the repository):
//
//	go run ./tools/licenses          check that the file is up to date
//	go run ./tools/licenses -write   regenerate it
//
// Only the permissive licenses in allowed are accepted; a module with
// another license, or without a license file, is an error.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const outName = "THIRD_PARTY_LICENSES.txt"

// allowed are the accepted licenses, as SPDX identifiers.
var allowed = map[string]bool{
	"MIT": true, "BSD-2-Clause": true, "BSD-3-Clause": true,
	"ISC": true, "Apache-2.0": true, "MPL-2.0": true,
}

// licenseNames are the license file names looked for, without extension
// (".txt" and ".md" are also tried); NOTICE and PATENTS are appended to the
// license when present.
var (
	licenseNames = []string{"LICENSE", "LICENCE", "COPYING"}
	extraNames   = []string{"NOTICE", "PATENTS"}
	extensions   = []string{"", ".txt", ".md"}
)

type module struct {
	path, version, dir string
}

type entry struct {
	title, spdx, text string
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("licenses: ")
	write := flag.Bool("write", false, "regenerate "+outName+" instead of checking it")
	flag.Parse()

	root, err := goOutput("", "env", "GOMOD")
	if err != nil || root == "" || root == os.DevNull {
		log.Fatalf("not in a Go module: %v", err)
	}
	out := filepath.Join(filepath.Dir(root), outName)
	text, err := generate(filepath.Dir(root))
	if err != nil {
		log.Fatal(err)
	}
	if *write {
		if err := os.WriteFile(out, []byte(text), 0o644); err != nil { // #nosec G306 -- committed text file, must stay world-readable
			log.Fatal(err)
		}
		return
	}
	old, err := os.ReadFile(out) // #nosec G304 -- fixed file name in the module root
	if err != nil {
		log.Fatalf("%v; run: go run ./tools/licenses -write", err)
	}
	if normalize(string(old)) != text {
		log.Fatalf("%s is out of date; run: go run ./tools/licenses -write", outName)
	}
}

func generate(dir string) (string, error) {
	goroot, err := goOutput(dir, "env", "GOROOT")
	if err != nil {
		return "", err
	}
	goText, err := readFirst(goroot, []string{"LICENSE"})
	if errors.Is(err, os.ErrNotExist) {
		goText = goLicense // distribution packages (e.g. Ubuntu's) leave it out
	} else if err != nil {
		return "", err
	}
	entries := []entry{{title: "Go standard library (https://go.dev)", text: goText}}

	mods, err := modules(dir)
	if err != nil {
		return "", err
	}
	for _, m := range mods {
		text, err := readFirst(m.dir, licenseNames)
		if err != nil {
			return "", fmt.Errorf("%s %s: no license file: %v", m.path, m.version, err)
		}
		for _, name := range extraNames {
			extra, err := readFirst(m.dir, []string{name})
			if err == nil {
				text += "\n" + strings.Repeat("-", 8) + " " + name + "\n\n" + extra
			} else if !errors.Is(err, os.ErrNotExist) {
				return "", err
			}
		}
		entries = append(entries, entry{title: m.path + " " + m.version, text: text})
	}

	var b strings.Builder
	b.WriteString("Third-party software included in tsnmp, with its license texts.\n")
	b.WriteString("Generated by \"go run ./tools/licenses -write\"; do not edit.\n")
	for _, e := range entries {
		e.spdx = detect(e.text)
		if !allowed[e.spdx] {
			return "", fmt.Errorf("%s: license not allowed: %s", e.title, e.spdx)
		}
		line := strings.Repeat("=", 78)
		fmt.Fprintf(&b, "\n%s\n%s\nLicense: %s\n%s\n\n%s", line, e.title, e.spdx, line, e.text)
	}
	return b.String(), nil
}

// modules returns the non-standard, non-main modules compiled into the
// linux and windows amd64 builds of the main package, sorted by path.
func modules(dir string) ([]module, error) {
	const format = `{{if not .Standard}}{{with .Module}}{{if not .Main}}` +
		`{{.Path}}{{"\t"}}{{.Version}}{{"\t"}}{{.Dir}}` +
		`{{end}}{{end}}{{end}}`
	seen := map[string]module{}
	for _, goos := range []string{"linux", "windows"} {
		out, err := goOutputEnv(dir, []string{"GOOS=" + goos, "GOARCH=amd64", "CGO_ENABLED=0"},
			"list", "-deps", "-f", format, ".")
		if err != nil {
			return nil, err
		}
		for _, line := range strings.Split(out, "\n") {
			f := strings.Split(line, "\t")
			if len(f) != 3 {
				continue
			}
			if f[2] == "" {
				return nil, fmt.Errorf("%s %s: module not downloaded", f[0], f[1])
			}
			seen[f[0]] = module{path: f[0], version: f[1], dir: f[2]}
		}
	}
	mods := make([]module, 0, len(seen))
	for _, m := range seen {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].path < mods[j].path })
	return mods, nil
}

// readFirst returns the normalized content of the first existing file
// among names × extensions in dir.
func readFirst(dir string, names []string) (string, error) {
	for _, name := range names {
		for _, ext := range extensions {
			data, err := os.ReadFile(filepath.Join(dir, name+ext)) // #nosec G304 -- license files of modules from go list
			if err == nil {
				return normalize(string(data)), nil
			}
			if !errors.Is(err, os.ErrNotExist) {
				return "", err
			}
		}
	}
	return "", fmt.Errorf("%s in %s: %w", strings.Join(names, "/"), dir, os.ErrNotExist)
}

// normalize makes texts comparable across platforms: LF line endings, no
// trailing spaces, no leading/trailing blank lines, one final newline.
func normalize(s string) string {
	lines := strings.Split(strings.ReplaceAll(s, "\r\n", "\n"), "\n")
	for i, l := range lines {
		lines[i] = strings.TrimRight(l, " \t\r")
	}
	return strings.Trim(strings.Join(lines, "\n"), "\n") + "\n"
}

// detect identifies a license text by its characteristic phrases; it
// returns a description instead of an SPDX identifier if it fails.
func detect(text string) string {
	t := strings.Join(strings.Fields(strings.ToLower(text)), " ")
	has := func(s string) bool { return strings.Contains(t, s) }
	switch {
	case has("apache license") && has("version 2.0"):
		return "Apache-2.0"
	case has("mozilla public license") && has("2.0"):
		return "MPL-2.0"
	case has("permission is hereby granted, free of charge"):
		return "MIT"
	case has("permission to use, copy, modify, and/or distribute this software for any purpose") ||
		has("permission to use, copy, modify, and distribute this software for any purpose"):
		return "ISC"
	case has("redistribution and use in source and binary forms"):
		if has("neither the name") || has("names of its contributors") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	}
	return "unknown license"
}

func goOutput(dir string, args ...string) (string, error) {
	return goOutputEnv(dir, nil, args...)
}

func goOutputEnv(dir string, env []string, args ...string) (string, error) {
	cmd := exec.Command("go", args...) // #nosec G204 -- arguments are fixed by the callers
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), env...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go %s: %v\n%s", strings.Join(args, " "), err, stderr.String())
	}
	return strings.TrimSpace(string(out)), nil
}

